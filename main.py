@handler.add(MessageEvent, message=TextMessageContent)
def handle_message(event):
    user_id = event.source.user_id  
    user_message = event.message.text
    
    # 獲取 AI 或系統直回的未切割原始文章
    raw_reply = get_prompt_and_respond(user_id, user_message)

    # 🛠️ 智慧切片優化
